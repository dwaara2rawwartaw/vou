#include <iostream>
#include <cmath>
using namespace std;
int main()
{
    int first, second;
    string x;
    if (x=="+")
    {
        cout << first + second << endl;
    }
    if (x=="-")
    {
        cout << first - second << endl;
    }
    if (x=="*")
    {
        cout << first * second << endl;
    }
    if (x=="/")
    {
        cout << first / second << endl;
    }
}